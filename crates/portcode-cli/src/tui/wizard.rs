//! `/create`: a guided start. What to recreate, how closely to look at it, what to build with, what you want.
//! State, keys and the prompt it produces; no rendering and no terminal (see `view::wizard`).
use crossterm::event::{KeyCode, KeyEvent, KeyModifiers};

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Kind {
    Website,
    App,
    Game,
    Format,
    Fresh,
}

/// Team runs lose the `port` agent's finish gate and bundled skill, so the prompt carries them.
const TEAM_RULES: &str = "Team: you lead and delegate with the `team` tool. Every worker must first load the rustport skill (`skill` tool) and follow it: evidence as observation, inference or unknown, goldens from the original, one small piece at a time. Do not say it is done until you have run `parity` yourself and it PASSED.\n";
const TEAM_RULES_FRESH: &str = "Team: you lead and delegate with the `team` tool: a plan from pm and techlead first, developers on different files, then tester and reviewer. Check the build and tests yourself before you say it is done.\n";

/// Where new code goes: always the folder PortCode was opened in.
const WHERE: &str = "Create all new source code inside the current folder (a subfolder such as <name>-rs/ is fine). Do not create anything outside it.\n";

impl Kind {
    pub const ALL: [Kind; 5] = [
        Kind::Website,
        Kind::App,
        Kind::Game,
        Kind::Format,
        Kind::Fresh,
    ];
    pub fn label(self) -> &'static str {
        match self {
            Kind::Website => "A website",
            Kind::App => "An app",
            Kind::Game => "A game",
            Kind::Format => "A file format",
            Kind::Fresh => "Nothing, start fresh",
        }
    }
    pub fn icon(self) -> &'static str {
        match self {
            Kind::Website => "◍",
            Kind::App => "▭",
            Kind::Game => "✥",
            Kind::Format => "▤",
            Kind::Fresh => "✦",
        }
    }
    pub fn source_label(self) -> Option<&'static str> {
        match self {
            Kind::Website => Some("Type the website's address:"),
            Kind::App => Some("Path to the program (an executable, .app or install folder):"),
            Kind::Game => Some("Path to the game (its folder, .app or executable):"),
            Kind::Format => Some("Path to a sample file of the format:"),
            Kind::Fresh => None,
        }
    }
    pub fn placeholder(self) -> &'static str {
        match self {
            Kind::Website => "https://example.com",
            Kind::App => "original/myapp",
            Kind::Game => "original/MyGame",
            Kind::Format => "inputs/save.dat",
            Kind::Fresh => "",
        }
    }
    pub fn default_text(self) -> &'static str {
        match self {
            Kind::Website => "Recreate this website",
            Kind::App => "Recreate this program, same behaviour",
            Kind::Game => "The same game, in Rust",
            Kind::Format => "Document the format and write a parser",
            Kind::Fresh => "A small tool that…",
        }
    }
    /// (label, hint for the prompt)
    pub fn stacks(self) -> &'static [(&'static str, &'static str)] {
        match self {
            Kind::Website => &[
                ("Rust + axum", "a Rust server (axum) that renders the pages"),
                (
                    "Static site",
                    "static HTML/CSS generated by a Rust build step",
                ),
                ("Leptos", "Leptos (Rust compiled to WebAssembly)"),
            ],
            Kind::App => &[
                ("Command line", "a command-line program (clap)"),
                ("Desktop, egui", "a desktop app with egui"),
                ("Desktop, Tauri", "a desktop app with Tauri"),
            ],
            Kind::Game => &[
                ("Bevy", "the Bevy engine"),
                (
                    "wgpu + winit",
                    "wgpu and winit behind small traits (own engine)",
                ),
                ("macroquad", "macroquad"),
            ],
            Kind::Format => &[
                (
                    "Parser crate + CLI",
                    "a Rust parser crate with a small CLI that dumps and re-writes the format",
                ),
                (
                    "Crate and tests",
                    "a Rust parser crate with round-trip tests only",
                ),
            ],
            Kind::Fresh => &[
                ("Rust", "plain Rust"),
                ("Command line", "a command-line program (clap)"),
                ("Rust + axum", "a Rust web service (axum)"),
            ],
        }
    }
}

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Field {
    Goal,
    Kind,
    Source,
    Look,
    Stack,
    Options,
    Text,
    Start,
}

const ORDER: [Field; 8] = [
    Field::Goal,
    Field::Kind,
    Field::Source,
    Field::Look,
    Field::Stack,
    Field::Options,
    Field::Text,
    Field::Start,
];

#[derive(Clone, Debug)]
pub struct Wizard {
    /// false: make my own version (agent `port`); true: just look inside (agent `reverse`, writes a spec).
    pub look_only: bool,
    pub kind: Kind,
    pub source: String,
    pub deep: bool,
    pub stack: usize,
    /// Own design and art instead of a 1:1 copy.
    pub own_art: bool,
    /// Run it with the `team` agent: a project manager, tech lead and workers in parallel.
    pub team: bool,
    /// Screenshots per feature and a generated site.
    pub proof: bool,
    pub text: String,
    pub focus: Field,
    pub error: Option<String>,
    /// What PortCode noticed about the source (file format, Unity backend, outside the project…).
    pub note: Option<String>,
    /// Opened by itself the first time PortCode starts in a folder: greets, and offers the normal interface.
    pub welcome: bool,
    /// Programs and games found in the opened folder; ← → on the path field switches between them.
    pub found: Vec<Found>,
    pub pick: usize,
    /// The path was filled in by detection, so a change of kind may replace it.
    pub auto: bool,
}

/// Something in the opened folder that looks like the program or game to recreate.
#[derive(Clone, Debug, PartialEq)]
pub struct Found {
    /// Relative to the folder PortCode was opened in; `.` for the folder itself.
    pub path: String,
    pub kind: Kind,
    /// One short phrase: "Unity 2021.3 · IL2CPP", "macOS app", "Windows program".
    pub what: String,
}

/// Look in `root` and up to three folders down for a game or program. Cheap and bounded: it never reads file
/// contents beyond four bytes, skips hidden and build folders, does not open `.app` bundles, and stops after a
/// few hundred entries per folder and a few dozen folders. If nothing is found but the folder is not a code
/// project either, the folder itself is offered (a game's install folder is a valid path).
pub fn detect(root: &std::path::Path) -> Vec<Found> {
    const SKIP: &[&str] = &[
        "target",
        "node_modules",
        "docs",
        "venv",
        "__pycache__",
        "original",
    ];
    const NOT_THE_PROGRAM: &[&str] = &[
        "unins",
        "uninstall",
        "vcredist",
        "vc_redist",
        "dxsetup",
        "crashhandler",
        "unitycrash",
        "crashpad",
        "setup",
        "installer",
        "updater",
        "dotnet",
        "redist",
        "notification_helper",
        "helper",
        "launcher_crash",
    ];
    const PROJECT_MARKERS: &[&str] = &[
        "Cargo.toml",
        "package.json",
        "pyproject.toml",
        "go.mod",
        "pom.xml",
        "CMakeLists.txt",
    ];
    let mut out: Vec<Found> = Vec::new();
    if let Some(u) = portcode_agent::tools::re::unity_summary(root) {
        out.push(Found {
            path: ".".into(),
            kind: Kind::Game,
            what: u,
        });
    }
    // the folder the user opened may itself be a macOS app (they opened `X.app`)
    if root.join("Contents/MacOS").is_dir() {
        out.push(Found {
            path: ".".into(),
            kind: Kind::App,
            what: "macOS app".into(),
        });
    }
    let mut queue: std::collections::VecDeque<(std::path::PathBuf, String, u8)> =
        std::collections::VecDeque::new();
    queue.push_back((root.to_path_buf(), String::new(), 0));
    let mut visited = 0usize;
    let mut root_has_files = false;
    let mut root_is_project = false;
    while let Some((dir, prefix, depth)) = queue.pop_front() {
        visited += 1;
        if visited > 60 {
            break;
        }
        let Ok(rd) = std::fs::read_dir(&dir) else {
            continue;
        };
        let entries: Vec<_> = rd.flatten().take(300).collect();
        let names: Vec<String> = entries
            .iter()
            .map(|e| e.file_name().to_string_lossy().to_string())
            .collect();
        if depth == 0 {
            root_has_files = names.iter().any(|n| !n.starts_with('.'));
            root_is_project = names.iter().any(|n| PROJECT_MARKERS.contains(&n.as_str()));
        }
        let game_like = names.iter().any(|n| {
            let l = n.to_lowercase();
            l.ends_with("_data")
                || l == "unityplayer.dll"
                || l == "gameassembly.dll"
                || l == "steam_appid.txt"
                || l.ends_with(".pak")
        });
        let kind = if game_like { Kind::Game } else { Kind::App };
        for e in &entries {
            let name = e.file_name().to_string_lossy().to_string();
            let lower = name.to_lowercase();
            let rel = format!("{prefix}{name}");
            let p = e.path();
            if name.starts_with('.') || NOT_THE_PROGRAM.iter().any(|n| lower.contains(n)) {
                continue;
            }
            let what = if lower.ends_with(".app") && p.join("Contents/MacOS").is_dir() {
                match portcode_agent::tools::re::unity_summary(&p) {
                    Some(u) => Some((Kind::Game, u)),
                    None => Some((kind, "macOS app".to_string())),
                }
            } else if lower.ends_with(".exe") {
                Some((kind, "Windows program".to_string()))
            } else if p.is_file() && is_native_executable(&p) {
                Some((kind, "program".to_string()))
            } else {
                None
            };
            match what {
                Some((k, w)) => {
                    if !out.iter().any(|f| f.path == rel) {
                        out.push(Found {
                            path: rel,
                            kind: k,
                            what: w,
                        });
                    }
                }
                None if depth < 3
                    && p.is_dir()
                    && !lower.ends_with(".app")
                    && !SKIP.contains(&name.as_str()) =>
                {
                    queue.push_back((p, format!("{rel}/"), depth + 1));
                }
                None => {}
            }
        }
    }
    // shallow finds first: the program next to the game's data is usually the one wanted
    out.sort_by_key(|f| (f.path != ".", f.path.matches('/').count()));
    out.truncate(6);
    if out.is_empty() && root_has_files && !root_is_project {
        out.push(Found {
            path: ".".into(),
            kind: Kind::App,
            what: "this folder: the install folder of the program or game".into(),
        });
    }
    out
}

fn is_native_executable(p: &std::path::Path) -> bool {
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        if !std::fs::metadata(p).is_ok_and(|m| m.permissions().mode() & 0o111 != 0) {
            return false;
        }
    }
    let mut head = [0u8; 4];
    std::fs::File::open(p)
        .and_then(|mut f| std::io::Read::read_exact(&mut f, &mut head))
        .is_ok()
        && matches!(
            head,
            [0x7f, b'E', b'L', b'F'] | [0xcf, 0xfa, 0xed, 0xfe] | [0xca, 0xfe, 0xba, 0xbe]
        )
}

/// What `Start` asks the app to do.
pub struct Launch {
    pub agent: &'static str,
    pub deep: bool,
    pub prompt: String,
}

pub enum Act {
    None,
    Cancel,
    Start(Launch),
}

impl Default for Wizard {
    fn default() -> Self {
        Self {
            look_only: false,
            kind: Kind::Website,
            source: String::new(),
            deep: false,
            stack: 0,
            own_art: false,
            team: false,
            proof: true,
            text: String::new(),
            focus: Field::Kind,
            error: None,
            note: None,
            welcome: false,
            found: Vec::new(),
            pick: 0,
            auto: false,
        }
    }
}

fn magic_name(head: &[u8]) -> Option<&'static str> {
    match head {
        [0x7f, b'E', b'L', b'F', ..] => Some("ELF executable"),
        [0xcf, 0xfa, 0xed, 0xfe, ..] | [0xce, 0xfa, 0xed, 0xfe, ..] => Some("Mach-O executable"),
        [0xca, 0xfe, 0xba, 0xbe, ..] => Some("Mach-O universal binary"),
        [b'M', b'Z', ..] => Some("Windows executable (PE)"),
        [b'P', b'K', 3, 4, ..] => Some("zip archive (maybe an APK or jar)"),
        _ => None,
    }
}

impl Wizard {
    /// Fill the path (and the kind) from what is in the folder, unless the user already typed something.
    pub fn detect_here(&mut self, root: &std::path::Path, allowed: &[String]) {
        self.found = detect(root);
        self.pick = 0;
        if self.source.trim().is_empty() {
            if let Some(f) = self.found.first().cloned() {
                self.kind = f.kind;
                self.source = f.path;
                self.auto = true;
                self.look_only = false;
                self.inspect(root, allowed);
            }
        }
    }

    /// Use detected item `i`.
    fn pick_found(&mut self, i: usize, root: &std::path::Path, allowed: &[String]) {
        if let Some(f) = self.found.get(i).cloned() {
            self.pick = i;
            self.kind = f.kind;
            self.source = f.path;
            self.auto = true;
            self.inspect(root, allowed);
        }
    }

    pub fn fields(&self) -> Vec<Field> {
        ORDER
            .iter()
            .copied()
            .filter(|f| *f != Field::Source || self.kind.source_label().is_some())
            .collect()
    }

    pub fn placeholder_text(&self) -> &'static str {
        self.kind.default_text()
    }

    fn step(&mut self, d: isize) {
        let f = self.fields();
        let i = f.iter().position(|x| *x == self.focus).unwrap_or(0) as isize;
        let n = f.len() as isize;
        self.focus = f[((i + d).rem_euclid(n)) as usize];
    }

    /// Look at the source on disk and say what it is. Cheap, and never reads more than a few bytes.
    pub fn inspect(&mut self, root: &std::path::Path, allowed: &[String]) {
        self.note = None;
        let src = self.source.trim();
        if src.is_empty() || matches!(self.kind, Kind::Website | Kind::Fresh) {
            return;
        }
        let p = if std::path::Path::new(src).is_absolute() {
            std::path::PathBuf::from(src)
        } else {
            root.join(src)
        };
        if !p.exists() {
            self.note = Some("not found yet".into());
            return;
        }
        let mut bits: Vec<String> = Vec::new();
        if self.kind == Kind::Game || self.kind == Kind::App {
            if let Some(u) = portcode_agent::tools::re::unity_summary(&p) {
                bits.push(u);
                if u_is_mono(bits.last().map(String::as_str)) {
                    bits.push("C# is readable with the dotnet tool".into());
                }
            }
        }
        if p.is_file() {
            let mut head = [0u8; 4];
            if std::fs::File::open(&p)
                .and_then(|mut f| std::io::Read::read_exact(&mut f, &mut head))
                .is_ok()
            {
                if let Some(n) = magic_name(&head) {
                    bits.push(n.into());
                }
            }
        } else if p.is_dir() {
            bits.push("folder".into());
        }
        let inside = p.canonicalize().ok().is_some_and(|c| {
            root.canonicalize().ok().is_some_and(|r| c.starts_with(r))
                || allowed.iter().any(|a| c.starts_with(a))
        });
        if !inside {
            bits.push(
                "outside the project: copy it into original/ or add its folder to allowed_dirs"
                    .into(),
            );
        }
        self.note = Some(bits.join(" · "));
    }

    pub fn on_key(&mut self, k: KeyEvent, root: &std::path::Path, allowed: &[String]) -> Act {
        let ctrl = k.modifiers.contains(KeyModifiers::CONTROL);
        let alt = k.modifiers.contains(KeyModifiers::ALT);
        self.error = None;
        match k.code {
            KeyCode::Esc => return Act::Cancel,
            KeyCode::Char('c') if ctrl => return Act::Cancel,
            KeyCode::Tab | KeyCode::Down if self.focus != Field::Text || k.code == KeyCode::Tab => {
                self.step(1);
                return Act::None;
            }
            KeyCode::BackTab => {
                self.step(-1);
                return Act::None;
            }
            KeyCode::Up if self.focus != Field::Text => {
                self.step(-1);
                return Act::None;
            }
            KeyCode::Char('s') if ctrl => return self.start(),
            _ => {}
        }
        let left = matches!(k.code, KeyCode::Left);
        let right = matches!(k.code, KeyCode::Right);
        match self.focus {
            Field::Goal => {
                if left || right || matches!(k.code, KeyCode::Char(' ') | KeyCode::Enter) {
                    self.look_only = if left {
                        false
                    } else if right {
                        true
                    } else {
                        !self.look_only
                    };
                    if self.look_only {
                        self.deep = true;
                    }
                }
            }
            Field::Kind => {
                let i = Kind::ALL.iter().position(|x| *x == self.kind).unwrap_or(0) as isize;
                let d = if left {
                    -1
                } else if right {
                    1
                } else {
                    0
                };
                if d != 0 {
                    self.kind = Kind::ALL[(i + d).rem_euclid(Kind::ALL.len() as isize) as usize];
                    self.stack = 0;
                    self.refill(root, allowed);
                } else if let KeyCode::Char(c @ '1'..='5') = k.code {
                    self.kind = Kind::ALL[(c as usize) - ('1' as usize)];
                    self.stack = 0;
                    self.refill(root, allowed);
                } else if k.code == KeyCode::Enter {
                    self.step(1);
                }
            }
            Field::Source => match k.code {
                KeyCode::Enter => self.step(1),
                KeyCode::Left | KeyCode::Right if !self.found.is_empty() => {
                    let n = self.found.len();
                    let next = if left {
                        (self.pick + n - 1) % n
                    } else {
                        (self.pick + 1) % n
                    };
                    self.pick_found(next, root, allowed);
                }
                KeyCode::Backspace => {
                    self.source.pop();
                    self.auto = false;
                    self.inspect(root, allowed);
                }
                KeyCode::Char(c) if !ctrl => {
                    if self.auto {
                        // typing over a detected path starts a fresh one
                        self.source.clear();
                        self.auto = false;
                    }
                    self.source.push(c);
                    self.inspect(root, allowed);
                }
                _ => {}
            },
            Field::Look => {
                if left || right || matches!(k.code, KeyCode::Char(' ') | KeyCode::Enter) {
                    self.deep = if left {
                        false
                    } else if right {
                        true
                    } else {
                        !self.deep
                    };
                    if self.look_only {
                        self.deep = true;
                    }
                }
            }
            Field::Stack => {
                let n = self.kind.stacks().len();
                if right || k.code == KeyCode::Char(' ') {
                    self.stack = (self.stack + 1) % n;
                } else if left {
                    self.stack = (self.stack + n - 1) % n;
                } else if k.code == KeyCode::Enter {
                    self.step(1);
                }
            }
            Field::Options => match k.code {
                KeyCode::Char('1') => self.own_art = !self.own_art,
                KeyCode::Char('2') => self.proof = !self.proof,
                KeyCode::Char('3') => self.team = !self.team,
                KeyCode::Left => self.own_art = !self.own_art,
                KeyCode::Right | KeyCode::Char(' ') => self.proof = !self.proof,
                KeyCode::Enter => self.step(1),
                _ => {}
            },
            Field::Text => match k.code {
                KeyCode::Enter if alt => self.text.push('\n'),
                KeyCode::Enter => return self.start(),
                KeyCode::Backspace => {
                    self.text.pop();
                }
                KeyCode::Char(c) if !ctrl => self.text.push(c),
                _ => {}
            },
            Field::Start => {
                if matches!(k.code, KeyCode::Enter | KeyCode::Char(' ')) {
                    return self.start();
                }
            }
        }
        Act::None
    }

    /// After a change of kind: an empty or auto-filled path is replaced by the first detected item of that kind.
    fn refill(&mut self, root: &std::path::Path, allowed: &[String]) {
        if self.source.trim().is_empty() || self.auto {
            let want_program = matches!(self.kind, Kind::App | Kind::Game);
            let i = self
                .found
                .iter()
                .position(|f| f.kind == self.kind)
                .or_else(|| {
                    want_program
                        .then(|| {
                            self.found
                                .iter()
                                .position(|f| matches!(f.kind, Kind::App | Kind::Game))
                        })
                        .flatten()
                });
            match i {
                Some(i) => {
                    if let Some(f) = self.found.get(i).cloned() {
                        self.pick = i;
                        self.source = f.path;
                        self.auto = true;
                    }
                }
                None => {
                    self.source.clear();
                    self.auto = false;
                }
            }
        }
        self.inspect(root, allowed);
    }

    fn start(&mut self) -> Act {
        self.error = None;
        let src = self.source.trim().to_string();
        if self.kind != Kind::Fresh && src.is_empty() {
            self.error = Some(format!(
                "{} Press tab to go back and fill it in.",
                self.kind.source_label().unwrap_or("Say what to recreate.")
            ));
            self.focus = Field::Source;
            return Act::None;
        }
        if self.kind == Kind::Website
            && !(src.starts_with("http://") || src.starts_with("https://"))
        {
            self.error = Some("A website address starts with http:// or https://".into());
            self.focus = Field::Source;
            return Act::None;
        }
        if self.kind == Kind::Fresh && self.text.trim().is_empty() {
            self.error = Some("Starting fresh needs a few words about what to make.".into());
            self.focus = Field::Text;
            return Act::None;
        }
        Act::Start(self.launch())
    }

    pub fn launch(&self) -> Launch {
        let src = self.source.trim();
        let want = if self.text.trim().is_empty() {
            self.kind.default_text().to_string()
        } else {
            self.text.trim().to_string()
        };
        let what = match self.kind {
            Kind::Website => format!("the website {src}"),
            Kind::App => format!("the program at {src}"),
            Kind::Game => format!("the game at {src}"),
            Kind::Format => format!("the file format of {src}"),
            Kind::Fresh => String::new(),
        };
        let stack = self
            .kind
            .stacks()
            .get(self.stack)
            .map(|s| s.1)
            .unwrap_or("Rust");
        let mut p = String::new();
        if self.kind == Kind::Fresh {
            if self.team {
                p += TEAM_RULES_FRESH;
            }
            p += &format!("Build this from scratch in Rust, using {stack}: {want}\n");
            p += "Plan first with todowrite, build in small slices, run the checks, and add a README.\n";
            p += WHERE;
            if self.proof {
                p += "Capture a screenshot per feature and finish with site_build.\n";
            }
            return Launch {
                agent: if self.team { "team" } else { "build" },
                deep: false,
                prompt: p,
            };
        }
        if self.look_only {
            p += &format!("Study {what} and explain it. Do not write port code.\n");
            p += "Pin it, survey it, record everything you learn with evidence_add (observation only for things you ran or saw; inference for what you read), and write docs/SPEC.md in your own words: behaviour, formats, rules, open unknowns.\n";
        } else {
            p += &format!("Recreate {what} in Rust ({stack}), following rustport.\n");
            p += if self.own_art {
                "Fidelity: the same features and behaviour, with its own design and art. Do not copy the original's assets, text or code.\n"
            } else {
                "Fidelity: 1:1 behaviour. Capture goldens from the original and prove parity before you say it is done; never claim parity without a parity PASS.\n"
            };
        }
        if !self.look_only {
            p += WHERE;
        }
        if self.deep {
            p += "Mode: deep. You may look inside the original (functions, disasm, decompile, emulate, hexdump, and for Unity or C#: unity, dotnet, unity_assets). Record what you read as inference.\n";
        } else {
            p += "Mode: clean-room. Observe the original from outside only (run it, feed inputs, compare outputs, screenshots, public docs). Do not read its private code or files.\n";
        }
        if !self.look_only && self.proof {
            p += "Proof: a screenshot per feature and site_build at the end.\n";
        }
        if self.team && !self.look_only {
            p += TEAM_RULES;
        }
        p += &format!("What I want: {want}");
        Launch {
            agent: if self.look_only {
                "reverse"
            } else if self.team {
                "team"
            } else {
                "port"
            },
            deep: self.deep || self.look_only,
            prompt: p,
        }
    }
}

